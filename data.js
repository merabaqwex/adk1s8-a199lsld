function seq(src, list) { // list: [[cd, fromTrack, toTrack], ...] → başlık dizisi
  const out = [];
  for (const [cd, a, b] of list) for (let t = a; t <= b; t++)
    out.push({ title: src[cd][t - 1], ref: `CD${cd}·${t}` });
  return out;
}
const mk = (arr) => arr.map((t) => (typeof t === "string" ? { title: t } : t));
